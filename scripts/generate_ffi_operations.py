#!/usr/bin/env python3
"""Generate the JSON operation adapters and reference from public SDK methods."""
import argparse
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
DOMAINS = {name: name.lower() for name in ('Search', 'Catalog', 'Home', 'Podcasts', 'Recents', 'Library', 'Playlists', 'Users', 'Extras', 'Devices', 'Jam', 'Blends')}
HEADER = '// Generated by scripts/generate_ffi_operations.py; do not edit.\n'


def methods():
    result = []
    for path in sorted((ROOT / 'crates/web/src/domains').glob('*.rs')):
        source = path.read_text()
        found = 0
        for block in re.finditer(r'impl(?:<[^>]*>)?\s+(\w+)(?:<[^>]*>)?\s*\{', source):
            domain = DOMAINS.get(block[1])
            if not domain:
                continue
            end = source.find('\n}', block.end())
            for method in re.finditer(r'pub async fn (\w+)\s*\((.*?)\)\s*->\s*(.*?)\s*\{', source[block.end():end], re.S):
                params = parse_params(method[2])
                result.append((domain, method[1], params, True, method[3]))
                found += 1
        assert found == len(re.findall(r'pub async fn ', source)), f'Unmapped public method in {path}'
    source = (ROOT / 'src/session.rs').read_text().split('    pub fn search(')[0]
    for method in re.finditer(r'pub (async )?fn (\w+)\s*\((.*?)\)\s*->\s*(.*?)\s*\{', source, re.S):
        if method[2] in {'new', 'with_host', 'builder', 'launch', 'connect', 'connect_web', 'login', 'shutdown', 'next_event', 'playback_mode', 'native_fallback_reason'}:
            continue
        result.append(('playback', method[2], parse_params(method[3]), bool(method[1]), method[4]))
    # These state helpers are implemented later in the same file.
    result.extend(('playback', name, [], asynchronous, response) for name, asynchronous, response in (
        ('state', False, 'Option<PlayerSnapshot>'), ('is_playing', False, 'bool'),
        ('current_track', False, 'Option<MediaItem>'), ('position_ms', False, 'u64'),
        ('volume', True, 'Result<f64, Error>'), ('audio_info', True, 'Result<AudioInfo, Error>'),
        ('toggle', True, 'Result<(), Error>')))
    assert len({(d, n) for d, n, _, _, _ in result}) == len(result)
    return sorted(result)


def parse_params(text):
    # Current public arguments have no comma-containing generic types. Fail rather than skip if that changes.
    params = []
    for argument in text.replace('\n', ' ').split(','):
        argument = argument.strip()
        if not argument or argument in ('&self', '&mut self'):
            continue
        name, kind = argument.split(':', 1)
        kind = kind.strip()
        assert '<' not in name and '>' not in name, argument
        params.append((name.strip(), kind))
    return params


def owned(kind):
    return {'&str': 'String', '&[String]': 'Vec<String>', 'Option<&str>': 'Option<String>',
            'Option<&[u8]>': 'Option<Vec<u8>>', '&Device': 'Device', 'impl Into<String>': 'String',
            'Duration': 'u64', 'Option<Duration>': 'Option<u64>'}.get(kind, kind)


def expression(name, kind):
    if kind in ('&str', '&[String]', '&Device'):
        return '&p.' + name
    if kind in ('Option<&str>', 'Option<&[u8]>'):
        return f'p.{name}.as_deref()'
    if kind == 'Duration':
        return f'std::time::Duration::from_millis(p.{name})'
    if kind == 'Option<Duration>':
        return f'p.{name}.map(std::time::Duration::from_millis)'
    return 'p.' + name


def outputs():
    groups = {}
    manifest = []
    for domain, name, params, asynchronous, response in methods():
        groups.setdefault(domain, [])
        fields = '\n'.join(f'                {n}: {owned(k)},' for n, k in params)
        if params:
            parse = '#[derive(serde::Deserialize)]\n            #[serde(deny_unknown_fields)]\n            struct Args {\n' + fields + '\n            }\n            let p: Args = parse(arguments)?;'
        else:
            parse = 'empty(arguments)?;'
        call = f'sdk.{name}' if domain == 'playback' else f'sdk.{domain}().{name}'
        call += '(' + ', '.join(expression(n, k) for n, k in params) + ')'
        if asynchronous:
            call += '.await?'
        if domain == 'playback' and name == 'set_quality':
            call = f'{{ let q = {call}; serde_json::json!({{"requested":q.requested,"effective":q.effective,"lossless_available":q.lossless_available}}) }}'
        groups[domain].append(f'        "{name}" => {{\n            {parse}\n            encode({call})\n        }}')
        manifest.append({'operation': f'{domain}.{name}', 'arguments': {n: owned(k) for n, k in params}, 'result': response.removeprefix('Result<').removesuffix(', Error>')})
    out = {}
    folder = ROOT / 'crates/spotcore-ffi/src/operations'
    for domain, arms in groups.items():
        body = '\n'.join(arms)
        helpers = ['encode'] + (['empty'] if 'empty(arguments)' in body else []) + (['parse'] if 'parse(arguments)' in body else [])
        imports = 'use super::{' + ', '.join(sorted(helpers)) + '};\nuse crate::BindingError;\nuse serde_json::Value;\n'
        for prefix, names in [('spotcore', ['AudioQuality', 'Command', 'Paging', 'QueueItem', 'RepeatMode', 'ShuffleMode']),
                              ('spotcore::web', ['Device', 'PlaylistAccess', 'SearchKind', 'TimeRange'])]:
            used = [name for name in names if re.search(r'\b' + name + r'\b', body)]
            if used:
                imports += 'use ' + prefix + '::{' + ', '.join(used) + '};\n'
        out[folder / f'{domain}.rs'] = HEADER + imports + f'\npub(super) async fn call(sdk: &mut spotcore::SpotCore, method: &str, arguments: Value) -> Result<Value, BindingError> {{\n    match method {{\n' + ',\n'.join(arms) + ',\n        _ => Err(super::unknown()),\n    }\n}\n'
    out[ROOT / 'bindings/operations.json'] = json.dumps(manifest, indent=2) + '\n'
    lines = ['# Binding operation reference', '', 'Generated from the public service methods and session playback controls. Run `python3 scripts/generate_ffi_operations.py --check` to detect missing adapters.', '', "Use `invoke(operation, arguments_json)` on a language session. Arguments are a JSON object with the names below. Results retain the Rust SDK's serialized field names; methods returning `Value` retain Spotify's original JSON. Errors use `BindingError`.", '', 'Direct duration arguments (`position`, `amount`) are integer **milliseconds**. `Command` arguments use the Rust externally tagged enum encoding; a nested `Duration` inside a command is `{"secs":30,"nanos":0}`. Prefer the named seek/rewind/context operations for millisecond arguments. `Paging` is `{"limit":20,"offset":0}`. Optional arguments may be omitted or null. JPEG covers are arrays of byte values, or null to remove a cover. Enum strings use Rust variant names: `Tracks`, `ShortTerm`, `Public`, `VeryHigh`, `Smart`, `Off`, etc. See the category guides for permissions, response types and feature limitations.', '', "A listed operation means it is exposed, not that every account supports it. `jam.join` preserves the SDK's current unsupported/unverified behavior. Session creation/login/shutdown and event consumption use the existing lifecycle methods; worker events are not fetched through `invoke`."]
    for domain in groups:
        lines.extend([f'## {domain.capitalize()}', '', '| Operation | Arguments | Result |', '| --- | --- | --- |'])
        for entry in manifest:
            if entry['operation'].startswith(domain + '.'):
                args = ', '.join(f'{n}: {k}' for n, k in entry['arguments'].items()).replace('|','\\|') or '{}'
                lines.append(f"| `{entry['operation']}` | `{args}` | `{entry['result']}` |")
        lines.append('')
    out[ROOT / 'docs/binding-operations.md'] = '\n'.join(lines)
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for path, content in outputs().items():
        if path.suffix == '.rs':
            content = subprocess.check_output(['rustfmt', '--emit', 'stdout', '--edition', '2024'], input=content, text=True)
        if args.check:
            existing = path.read_text() if path.exists() else ''
            if existing != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        raise SystemExit('Stale binding operations: ' + ', '.join(stale))


if __name__ == '__main__':
    main()
